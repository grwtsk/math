#!/usr/bin/env python3
"""Independent exact-integer controls for arithmetic prime Jacobi moments.

No zeta zero, Alpoge theorem, model output, or fitted spectral parameter
enters the prime-only Jacobi operator. This is finite numerical evidence,
not a Lean proof or a source equality with the completed zeta function.
"""
from __future__ import annotations
from fractions import Fraction
from math import isqrt
import json


def primes_first(count: int) -> list[int]:
    primes = []
    n = 2
    while len(primes) < count:
        if all(n % p for p in primes if p * p <= n):
            primes.append(n)
        n += 1
    return primes


def action(bonds: list[int], values: list[int]) -> list[int]:
    n = len(values)
    return [
        (bonds[i - 1] * values[i - 1] if i else 0)
        + (bonds[i] * values[i + 1] if i + 1 < n else 0)
        for i in range(n)
    ]


def root_moment(bonds: list[int], degree: int) -> int:
    f = [1] + [0] * len(bonds)
    for _ in range(degree):
        f = action(bonds, f)
    return f[0]


def determinant_integer(rows: list[list[int]]) -> int:
    # Fraction-free Bareiss elimination, so huge determinants stay exact.
    size = len(rows)
    if not size:
        return 1
    matrix = [row[:] for row in rows]
    previous = 1
    sign = 1
    for k in range(size - 1):
        if matrix[k][k] == 0:
            pivot_row = next((i for i in range(k + 1, size)
                              if matrix[i][k]), None)
            if pivot_row is None:
                return 0
            matrix[k], matrix[pivot_row] = matrix[pivot_row], matrix[k]
            sign *= -1
        pivot = matrix[k][k]
        for i in range(k + 1, size):
            for j in range(k + 1, size):
                numerator = matrix[i][j] * pivot - matrix[i][k] * matrix[k][j]
                assert numerator % previous == 0
                matrix[i][j] = numerator // previous
        for i in range(k + 1, size):
            matrix[i][k] = 0
        previous = pivot
    return sign * matrix[-1][-1]


def check() -> dict:
    primes = primes_first(24)
    tested = 0
    for size in range(1, 21):
        bonds = primes[:size - 1]
        f = [(3 * i - 11) * (-1) ** i for i in range(size)]
        twist = lambda x: [(-1) ** i * v for i, v in enumerate(x)]
        jf = action(bonds, f)
        assert twist(twist(f)) == f
        assert action(bonds, twist(f)) == [-v for v in twist(jf)]
        jjf = action(bonds, jf)
        assert sum(a * b for a, b in zip(f, jjf)) == sum(v * v for v in jf)
        assert action(bonds, twist(jf)) == [-v for v in twist(jjf)]
        tested += 1

    bonds = primes[:8]
    moments = [root_moment(bonds, j) for j in range(18)]
    determinants = [1]
    for n in range(1, 10):
        hankel = [[moments[i + j] for j in range(n)] for i in range(n)]
        determinants.append(determinant_integer(hankel))
        expected = 1
        for j in range(n - 1):
            expected *= bonds[j] ** (2 * (n - 1 - j))
        assert determinants[n] == expected
    recovered = []
    for k in range(8):
        squared = Fraction(determinants[k + 2] * determinants[k],
                           determinants[k + 1] ** 2)
        assert squared.denominator == 1
        prime = isqrt(squared.numerator)
        assert prime * prime == squared.numerator
        recovered.append(prime)
    assert recovered == bonds
    assert [moments[n] for n in (0, 2, 4, 6, 8)] == [1, 4, 52, 1576, 98788]

    return {
        "status": "EXACT_PRIME_JACOBI_MOMENT_CONTROLS_PASS",
        "source": "actual primes generated by integer trial division",
        "source_zeros_in_operator": False,
        "jacobi_sections_checked": tested,
        "mirror_anticommutation": "PASS",
        "squared_quadratic_identity": "PASS",
        "hankel_ranks": list(range(10)),
        "hankel_determinants": [str(d) for d in determinants],
        "even_root_moments": [moments[n] for n in (0, 2, 4, 6, 8)],
        "recovered_prime_bonds": recovered,
        "fully_formalized_hankel_inverse": False,
        "source_zeta_spectrum_correspondence": "OPEN",
        "lean_kernel_replay": "NOT_RUN",
    }


if __name__ == "__main__":
    print(json.dumps(check(), indent=2))
